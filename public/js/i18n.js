let current = "vi";

export const languages = () => Object.keys(TEXT);
export const currentLanguage = () => current;
export const t = (key) => TEXT[current][key] ?? TEXT.en[key] ?? key;

export const setLanguage = (language, root = document) => {
  current = TEXT[language] ? language : "vi";
  document.documentElement.lang = current;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.title = t("title");
};

export const textKeys = (language) => Object.keys(TEXT[language] || {});
